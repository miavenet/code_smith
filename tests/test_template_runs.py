class Refactoring(TemplateRun):
    MODULE = 'def area(w, h):\n    return w * h\n\n\ndef perimeter(w, h):\n    return 2 * (w + h)\n'
    CHAR = ('import sys\nsys.path.insert(0, "src")\nimport shapes\n'
            'assert shapes.area(2, 3) == 6\nassert shapes.perimeter(2, 3) == 10\n')

    def test_three_steps_each_one_commit(self):
        """tpl: the refactoring template runs three chained steps, one commit each; a step over its
        diff budget, or one that breaks the characterisation tests, is sent back (TPL-14); the final
        panel sees the cumulative diff from characterise's commit: the three steps' changes and the
        report, and is told it spans from characterise (TPL-21)"""
        self.write("src/shapes/__init__.py", self.MODULE)
        self.generate("refactoring", {
            "name": "split-shapes", "brief": "briefs/split-pricing.md",
            "invariant": "area and perimeter return what they return today",
            "area": "src/shapes/**", "char_tests": "tests/characterisation/test_shapes.py",
            "test_char": "python3 -B tests/characterisation/test_shapes.py",
            "suite": "python3 -B tests/characterisation/test_shapes.py",
            "steps": ["Move area to area.py", "Move perimeter to perimeter.py", "Document the package"],
            "step_max_lines": 20,
        }, "split.toml")
        area = 'def area(w, h):\n    return w * h\n'
        perimeter = 'def perimeter(w, h):\n    return 2 * (w + h)\n'
        step1 = {"src/shapes/area.py": area,
                 "src/shapes/__init__.py": 'from .area import area\n\n\n' + perimeter}
        self.script({
            "characterise": [{"write": {"tests/characterisation/test_shapes.py": self.CHAR},
                              "answer": done()}],
            "characterise.review.meticulous-mira": [PASS],
            "characterise.review.principled-priya": [PASS],
            "characterise.review.steadfast-stefan": [PASS],
            "step-1": [{"write": dict(step1, **{"src/shapes/big.py": "x = 1\n" * 40}), "answer": done()},
                       {"write": step1, "remove": ["src/shapes/big.py"], "answer": done()}],
            "step-1.review.gatekeeper-gao": [PASS],
            "step-1.review.principled-priya": [PASS],
            "step-2": [{"write": {"src/shapes/perimeter.py": 'def perimeter(w, h):\n    return w + h\n',
                                  "src/shapes/__init__.py": 'from .area import area\nfrom .perimeter import perimeter\n'},
                        "answer": done()},
                       {"write": {"src/shapes/perimeter.py": perimeter}, "answer": done()}],
            "step-2.review.gatekeeper-gao": [PASS],
            "step-2.review.principled-priya": [PASS],
            "step-3": [{"write": {"src/shapes/__init__.py": '"""Shapes."""\nfrom .area import area\n'
                                                            'from .perimeter import perimeter\n'},
                        "answer": done()}],
            "step-3.review.gatekeeper-gao": [PASS],
            "step-3.review.principled-priya": [PASS],
            "final": [{"write": {"docs/refactor/split-shapes/final.md": "Three steps; surface unchanged.\n"},
                       "answer": done()}],
            "final.review.principled-priya": [PASS],
            "final.review.steadfast-stefan": [PASS],
        })
        self.sign_off()
        state = self.the_run().state["tasks"]
        self.assertEqual([state[t]["status"] for t in ("characterise", "step-1", "step-2", "step-3", "final")],
                         ["accepted"] * 5)
        self.assertEqual([state[t]["attempts"] for t in ("step-1", "step-2", "step-3")], [2, 2, 1])
        with open(self.task_file("step-1", "attempt-2", "feedback.md"), encoding="utf-8") as fh:
            self.assertIn("the change is larger than the task's diff budget", fh.read())
        with open(self.task_file("step-2", "attempt-2", "feedback.md"), encoding="utf-8") as fh:
            self.assertIn("python3 -B tests/characterisation/test_shapes.py", fh.read())
        commits = self.git_out("log", "--format=%H", "main..HEAD").split()
        self.assertEqual(len(commits), 5)              # characterise, three steps, final
        for tid in ("step-1", "step-2", "step-3"):
            self.assertIn(state[tid]["commit"], commits)
        self.assertEqual(len({state[t]["commit"] for t in ("step-1", "step-2", "step-3")}), 3)
        characterised = self.git_out("rev-parse", state["characterise"]["commit"] + "^{tree}")
        for rid in ("final.review.principled-priya", "final.review.steadfast-stefan"):
            with open(self.task_file(rid, "round-1", "diff.patch"), encoding="utf-8") as fh:
                patch = fh.read()
            for path in ("src/shapes/area.py", "src/shapes/perimeter.py", "src/shapes/__init__.py",
                         "docs/refactor/split-shapes/final.md"):
                self.assertIn("+++ b/" + path, patch)
            self.assertIn('+"""Shapes."""', patch)                      # step 3's change
            self.assertNotIn("tests/characterisation", patch)           # characterise's own work
            with open(self.task_file(rid, "round-1", "prompt.md"), encoding="utf-8") as fh:
                self.assertIn("This diff spans from 'characterise'", fh.read())
            verdict = self.read_json(rid, "round-1", "verdict.json")
            self.assertEqual(verdict["base"], characterised)
            self.assertEqual(verdict["diff_from"]["task"], "characterise")
        self.check_invariants()


class Optimisation(TemplateRun):
    """The pilot optimisation template, wired end to end. The benchmark is a stand-in: it reports
    the module's COST constant per update with a fixed spread, so the numbers are the same on any
    machine and the test proves the wiring, never a measurement."""

    BOOK = ('COST = {cost}\n\n\ndef best_bid(levels):\n'
            '    """The highest price with a positive quantity, or None."""\n'
            '    return max((p for p, q in levels{cond}), default=None)\n')
    SUITE = ('import sys\nimport unittest\n\nsys.path.insert(0, "src")\nimport book  # noqa: E402\n'
             '\n\nclass Book(unittest.TestCase):\n    def test_best_bid(self):\n'
             '        self.assertEqual(book.best_bid([(10, 1), (11, 2)]), 11)\n\n\n'
             'if __name__ == "__main__":\n    unittest.main()\n')
    BENCH = ('import json\nimport os\nimport sys\n\nsys.path.insert(0, "src")\n'
             'import book  # noqa: E402\n\n'
             'out = sys.argv[1]\nos.makedirs(os.path.dirname(out), exist_ok=True)\n'
             'runs = [[book.COST + (i * 7919 + r) % 13 for i in range(200)] for r in range(5)]\n'
             'with open(out, "w", encoding="utf-8") as fh:\n'
             '    json.dump({"command": "python3 -B bench/book/bench_book.py", "pinning": "none",\n'
             '               "warm": True,\n'
             '               "benchmarks": [{"bench": "update", "unit": "ns",\n'
             '                               "runs": runs}]},\n'
             '              fh)\n')
    ORACLE = ('import sys\n\nsys.path.insert(0, "src")\nimport book  # noqa: E402\n\n'
              'RECORDED = [([(10, 1), (11, 2)], 11), ([(10, 1), (11, 0)], 10), ([], None)]\n'
              'for levels, want in RECORDED:\n'
              '    got = book.best_bid(levels)\n'
              '    if got != want:\n'
              '        sys.exit(f"equivalence: best_bid({levels}) is {got}, recorded {want}")\n'
              'print("equivalence: 3 recorded cases match")\n')
    BENCH_CMD = "python3 -B bench/book/bench_book.py build/bench/book.json"

    def setup_project(self):
        self.write("src/book/__init__.py", self.BOOK.format(cost=100, cond=" if q > 0"))
        self.write("tests/test_book.py", self.SUITE)
        with open(os.path.join(HERE, "..", "examples", "tools", "bench_contract.py"),
                  encoding="utf-8") as fh:
            self.write("tools/bench_contract.py", fh.read())
        benches = os.path.join(HERE, "..", "examples", "templates", "benches")
        rules = ""
        for name in ("cpp-standards.md", "performance.md"):         # appended into one file
            with open(os.path.join(benches, name), encoding="utf-8") as fh:
                rules += fh.read() + "\n"
        self.write("benches/rules.md", rules)
        self.generate("optimisation", {
            "name": "book-update-latency", "brief": "briefs/book-update-latency.md",
            "src": "src/book/**", "protected": ["tests/test_book.py"],
            "test_cmd": "python3 -B tests/test_book.py",
            "bench": "bench/book/**", "bench_cmd": self.BENCH_CMD,
            "bench_out": "build/bench/book.json", "baseline": "bench/book/baseline.json",
            "threshold_pct": 10, "repetitions": 5,
            "equivalence_test": "tests/equivalence/**",
            "equivalence_cmd": "python3 -B tests/equivalence/test_book.py",
            "hot_path": "best_bid on a warm book", "latency_budget_p99_ns": 150,
            "rules_file": "benches/rules.md",
            # the session reference: HEAD (the accepted baseline) exported and benchmarked here
            "baseline_bench_cmd": ["rm -rf build/base && mkdir -p build/base && git archive HEAD "
                                   "| tar -x -C build/base && cd build/base && python3 -B "
                                   "bench/book/bench_book.py ../bench/book-session.json"],
            "session_ref": "build/bench/book-session.json",
        }, "book-opt.toml")
        self.write(".gitignore", "__pycache__/\nbuild/\n")     # bench_out lies in an ignored path
        self.commit()

    def baseline_steps(self):
        """The baseline's author writes the benchmark and the oracle, then runs the benchmark
        and copies its output: no number is written by hand."""
        return {
            "baseline": [{"write": {"bench/book/bench_book.py": self.BENCH,
                                    "tests/equivalence/test_book.py": self.ORACLE},
                          "run": [self.BENCH_CMD + " && cp build/bench/book.json "
                                  "bench/book/baseline.json"],
                          "answer": done()}],
            "baseline.review.nanosecond-nadia": [PASS],
            "baseline.review.meticulous-mira": [PASS],
        }

    def read_text(self, task, *parts):
        with open(self.task_file(task, *parts), encoding="utf-8") as fh:
            return fh.read()

    def gate_log(self, attempt):
        return self.read_text("optimise", f"attempt-{attempt}", "gate.log")

    def latest_round(self, task):
        return sorted(n for n in os.listdir(self.task_file(task)) if n.startswith("round-"))[-1]

    def test_optimisation_runs_its_gates_in_order_and_sends_regressions_back(self):
        """wf: a scripted run of the optimisation template: the baseline is committed from the
        benchmark's own output; a candidate slower by three times the threshold is sent back by
        the contract gate after the suite and the benchmark ran; one that changes a recorded
        output is sent back by the equivalence check; the accepted candidate's gate evidence holds
        the lines a performance reviewer cites, and her prompt carries them with the budget
        (WF-32)"""
        self.setup_project()
        slow = self.BOOK.format(cost=140, cond=" if q > 0")
        wrong = self.BOOK.format(cost=50, cond="")             # faster, and wrong on an empty level
        fast = self.BOOK.format(cost=50, cond=" if q > 0")
        steps = self.baseline_steps()
        steps.update({
            "optimise": [{"write": {"src/book/__init__.py": text}, "answer": done()}
                         for text in (slow, wrong, fast)],
            "report": [{"write": {"docs/reports/book-update-latency.md":
                                  "p99 112 ns before, 62 ns after, as the contract printed.\n"},
                        "answer": done()}],
            "report.review.protocol-petra": [PASS],
        })
        for name in ("nanosecond-nadia", "gatekeeper-gao", "meticulous-mira", "concerned-carlos"):
            steps[f"optimise.review.{name}"] = [PASS, PASS, PASS]
        self.script(steps)
        self.sign_off()
        state = self.the_run().state["tasks"]
        self.assertEqual({t: state[t]["status"] for t in ("baseline", "optimise", "report")},
                         dict.fromkeys(("baseline", "optimise", "report"), "accepted"))
        self.assertEqual(state["optimise"]["attempts"], 3)
        baseline = self.git_out("show", f"{state['baseline']['commit']}:bench/book/baseline.json")
        self.assertIn('"pinning": "none"', baseline)
        self.assertIn("result: pass (exit 0)", self.read_text("baseline", "attempt-1", "gate.log"))
        # attempt 1: the suite and the benchmark pass, then the contract fails on the regression
        log = self.gate_log(1)
        contract = "$ python3 tools/bench_contract.py bench/book/baseline.json build/bench/"
        self.assertLess(log.index("$ python3 -B tests/test_book.py"),
                        log.index("$ " + self.BENCH_CMD))
        self.assertLess(log.index("$ " + self.BENCH_CMD), log.index(contract))
        self.assertIn("budget p99 <= 150 ns: EXCEEDED (update candidate p99 152 ns)", log)
        delta = float(log.split("update  p99 ")[1].split("%")[0])
        self.assertGreaterEqual(delta, 30.0)                     # 3 x the threshold of 10%
        self.assertIn("): regression\nresult: regression (exit 1)", log)
        self.assertIn("session drift: the baseline re-measured in this session is within 0.0%",
                      log)
        self.assertIn("update  session    ns    1000   106  112  112    112", log)
        self.assertIn("result: regression (exit 1)",
                      self.read_text("optimise", "attempt-2", "feedback.md"))
        # attempt 2: faster, and wrong on a recorded input: the equivalence check sends it back
        self.assertIn("result: pass (exit 0)", self.gate_log(2))
        told = self.read_text("optimise", "attempt-3", "feedback.md")
        self.assertIn("python3 -B tests/equivalence/test_book.py", told)
        self.assertIn("best_bid([(10, 1), (11, 0)]) is 11, recorded 10", told)
        # attempt 3, accepted: the lines a performance reviewer would cite
        log = self.gate_log(3)
        for line in ("PF-M01 baseline: present, 1 benchmark(s)",
                     "PF-M02 command: python3 -B bench/book/bench_book.py; pinning: none",
                     "PF-M03 warm; percentiles below",
                     "PF-M04 threshold: 10% on p50 and p99",
                     "budget p99 <= 150 ns: met (update candidate p99 62 ns)",
                     "update  baseline   ns    1000   106  112  112    112",
                     "update  candidate  ns    1000   56   62   62     62",
                     "pass: faster\nresult: pass (exit 0)"):
            self.assertIn(line, log)
        rid = "optimise.review.nanosecond-nadia"
        prompt = self.read_text(rid, self.latest_round(rid), "prompt.md")
        for text in ("pass: faster\\nresult: pass (exit 0)", '"latency_budget_p99_ns": 150',
                     '"hot_path": "best_bid on a warm book"', "- **PF-M04 ",
                     '"perspective": "concerned-carlos"'):
            self.assertIn(text, prompt)
        self.check_invariants()

    def test_a_regression_that_stays_fails_the_task(self):
        """wf: a candidate that stays slower by three times the threshold fails the optimise
        task on the contract gate, and nothing of it is committed (WF-32)"""
        self.setup_project()
        slow = {"write": {"src/book/__init__.py": self.BOOK.format(cost=140, cond=" if q > 0")},
                "answer": done()}
        steps = self.baseline_steps()
