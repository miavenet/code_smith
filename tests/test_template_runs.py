"""The shipped debugging, refactoring and optimisation templates, run end to end with the scripted
agent (scenarios ACC-29, TPL-14, TPL-19, TPL-21 and WF-32 of docs/06-scenarios.md).
Each workflow is generated by `runner new`
in a scratch repository holding a seeded defect or a small module, given the scripted agent in
place of `claude` (an ordinary edit of the generated file), and driven model-free through `start`,
`approve` and `resume`.

Every test ends with `check_invariants`: every accepted commit is exactly the verified candidate."""

